val localProperties = Properties().apply {
    val localPropertiesFile = rootProject.file("local.properties")
    if (localPropertiesFile.exists()) {
        localPropertiesFile.inputStream().use { load(it) }
    }
}
val groqApiKey: String = (localProperties.getProperty("GROQ_API_KEY") ?: "").trim()

/**
 * Release signing credentials, read from a gitignored `keystore.properties` at the repo root
 * (see `keystore.properties.example`). Absent on machines that only build debug — the release
 * signingConfig is then simply not wired up, rather than failing configuration.
 */
val keystoreProperties = Properties().apply {
    val keystorePropertiesFile = rootProject.file("keystore.properties")
    if (keystorePropertiesFile.exists()) {
        keystorePropertiesFile.inputStream().use { load(it) }
    }
}
val hasReleaseSigning: Boolean = keystoreProperties.getProperty("storeFile") != null

android {
    namespace = "com.olab.studyqb"
    compileSdk {
        version = release(36) {
            minorApiLevel = 1
        }
    }

    defaultConfig {
        applicationId = "com.olab.studyqb.android"
        minSdk = 24
        targetSdk = 36
        versionCode = 3
        versionName = "1.2"

        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"

        buildConfigField("String", "GROQ_API_KEY", "\"$groqApiKey\"")
    }

    signingConfigs {
        if (hasReleaseSigning) {
            create("release") {
                storeFile = rootProject.file(keystoreProperties.getProperty("storeFile"))
                storePassword = keystoreProperties.getProperty("storePassword")
                keyAlias = keystoreProperties.getProperty("keyAlias")
                keyPassword = keystoreProperties.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = false
            proguardFiles(
                getDefaultProguardFile("proguard-android-optimize.txt"),
                "proguard-rules.pro"
            )
            if (hasReleaseSigning) {
                signingConfig = signingConfigs.getByName("release")
            }
        }
    }

    buildFeatures {
        compose = true
        buildConfig = true
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_11
        targetCompatibility = JavaVersion.VERSION_11
        isCoreLibraryDesugaringEnabled = true
    }

    androidResources {
        // assets/dataset.jsonl is 4.6 MB of cached clue analysis. Left compressed, every
        // CachedClueDataSource lookup has to inflate the whole thing — measured at ~3.2s per
        // full scan on the emulator, against ~11ms for the same scan on the JVM. Storing it
        // uncompressed makes the read mmap-able. It costs on-device storage, not download
        // size, since Play compresses the delivered artifact regardless.
        noCompress += "jsonl"
    }

    packaging {
        resources {
            excludes += "/META-INF/{AL2.0,LGPL2.1}"
        }
    }

    testOptions {
        unitTests {
            isReturnDefaultValues = true
        }
    }
}

